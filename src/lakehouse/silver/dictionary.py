"""Generate the silver data dictionary (``docs/data-dictionary.md``) from code.

Column names and types come from actually building every registered silver table, plus
its geo step, against empty bronze tables in a throwaway in-memory database. Descriptions
come from the column specs (``Column.description``), the modules' ``DERIVED_DESCRIPTIONS``,
``LINEAGE_DESCRIPTIONS`` and ``geo.GEO_COLUMN_DESCRIPTIONS``. A column without a
description raises ``ValueError``, so the dictionary is complete by construction.
``check()`` compares the committed file with a fresh render.
"""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path

from lakehouse.reference import SEEDS
from lakehouse.silver import crimes, geo, service_requests, taxi_trips
from lakehouse.silver.typing import LINEAGE_DESCRIPTIONS
from lakehouse.storage.bronze import BronzeStore

DEFAULT_PATH = Path(__file__).resolve().parents[3] / "docs" / "data-dictionary.md"
MODULES = (crimes, service_requests, taxi_trips)
DOC_LINKS = {
    "silver.crimes": "silver-crimes.md",
    "silver.service_requests": "silver-311.md",
    "silver.taxi_trips": "silver-taxi.md",
}


@dataclass(frozen=True)
class ColumnDoc:
    name: str
    type: str
    origin: str  # raw field, "derived", "lineage", "geo"
    description: str


def _md(text: str) -> str:
    return text.replace("|", "\\|")


def describe_table(module) -> list[ColumnDoc]:
    """Columns of a silver table in physical order, with origin and description."""
    store = BronzeStore(":memory:")
    try:
        key = next(c.raw for c in module.COLUMNS)
        store.write(module.SOURCE, [], primary_key=key)
        module.build(store)
        if module.TABLE in geo.GEO_TABLES:
            geo.clean_table(store.con, module.TABLE, geo.AreaIndex())
        physical = store.con.execute(f"DESCRIBE {module.TABLE}").fetchall()
    finally:
        store.close()

    by_name = {c.name: c for c in module.COLUMNS}
    derived = getattr(module, "DERIVED_DESCRIPTIONS", {})
    geo_docs = {}
    for pc in geo.GEO_TABLES.get(module.TABLE, []):
        for suffix, text in geo.GEO_COLUMN_DESCRIPTIONS.items():
            where = f" ({pc.prefix.rstrip('_')})" if pc.prefix else ""
            geo_docs[f"{pc.prefix}{suffix}"] = text + where
    docs = []
    for name, typ, *_ in physical:
        if name in by_name:
            c = by_name[name]
            origin, text = f"`{c.raw}` ({c.kind})", c.description
        elif name in derived:
            origin, text = "derived", derived[name]
        elif name in LINEAGE_DESCRIPTIONS:
            origin, text = "lineage", LINEAGE_DESCRIPTIONS[name]
        elif name in geo_docs:
            origin, text = "geo", geo_docs[name]
        else:
            raise ValueError(f"{module.TABLE}.{name} has no description")
        if not text:
            raise ValueError(f"{module.TABLE}.{name} has an empty description")
        docs.append(ColumnDoc(name, typ, origin, text))
    return docs


def render() -> str:
    out = [
        "# Data dictionary",
        "",
        "<!-- Generated by `lakehouse docs dictionary` from the silver column specs. "
        "Do not edit by hand; CI fails if this file is stale. -->",
        "",
        "Every column of every silver table, with its type, where it comes from and what it",
        "means. Types are read from real (empty) builds, so they match the database exactly.",
        "",
        "**Origin**: `field` (kind) = typed from that raw bronze field with the given cleaning",
        "kind ([typing rules](silver-crimes.md#cleaning-rules)); **derived** = computed from",
        "other columns; **lineage** = carried from bronze; **geo** = added by",
        "[geo cleanup](geo-cleanup.md).",
        "",
        "| Table | Grain | Columns |",
        "|---|---|---|",
    ]
    tables = [(m, describe_table(m)) for m in MODULES]
    for m, cols in tables:
        anchor = m.TABLE.replace(".", "")
        out.append(f"| [`{m.TABLE}`](#{anchor}) | {_md(m.GRAIN)} | {len(cols)} |")
    for m, cols in tables:
        out += [
            "",
            f"## {m.TABLE}",
            "",
            f"{_md(m.GRAIN)} Source: `bronze.{m.SOURCE}__latest`. "
            f"Details: [{DOC_LINKS[m.TABLE]}]({DOC_LINKS[m.TABLE]}).",
            "",
            "| Column | Type | Origin | Description |",
            "|---|---|---|---|",
        ]
        out += [
            f"| `{c.name}` | {c.type} | {c.origin} | {_md(c.description)} |" for c in cols
        ]
        checks = getattr(m, "QUALITY_CHECKS", {})
        if checks:
            out += ["", "Quality checks (rows counted, never dropped):", ""]
            out += [f"- `{name}`: `{_md(cond)}`" for name, cond in checks.items()]
    out += ["", "## Reference tables", "", "Loaded from `seeds/` ([reference data]"
            "(reference-data.md)); each also has a `<name>_history` SCD2 table ([SCD2](scd2.md)).",
            ""]
    for seed in SEEDS.values():
        cols = ", ".join(f"`{c}` {t}" for c, t in seed.columns.items())
        out.append(f"- `{seed.table}`: {seed.description}. Key `{seed.key}`. Columns: {cols}.")
    return "\n".join(out) + "\n"


def write(path: Path | str = DEFAULT_PATH) -> Path:
    path = Path(path)
    path.write_text(render())
    return path


def check(path: Path | str = DEFAULT_PATH) -> bool:
    """True when the file at ``path`` matches a fresh render."""
    path = Path(path)
    return path.exists() and path.read_text() == render()
